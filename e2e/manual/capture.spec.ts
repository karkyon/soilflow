/* 操作マニュアル（docs/20_操作マニュアル.md）の画面写真。受付編 → 本社編 → 管理者編の順に、実際の流れで撮る */
import { expect, Page, test } from '@playwright/test';
import { join } from 'node:path';
import { expectPdfOpened, lastMonth, login, newUser, state, toast } from '../tests/helpers';

test.describe.configure({ mode: 'serial' });
const OUT = join(__dirname, '..', '..', 'docs', 'manual', 'img');
const shot = async (p: Page, name: string, o: { full?: boolean } = {}) => { await p.waitForTimeout(400); await p.screenshot({ path: join(OUT, `${name}.png`), fullPage: !!o.full, animations: 'disabled', caret: 'hide' }); };
const dialog = (p: Page) => p.getByRole('dialog');
const row = (p: Page, v: string) => p.locator('tbody tr').filter({ has: p.getByRole('button', { name: v, exact: true }) });
const nowCell = (p: Page, v: string) => row(p, v).locator('td.bg-gold-pale');
let reception: Page;

test('受付編', async ({ browser, page }) => {
  await page.goto('/login/');
  await page.getByLabel('ログインID').fill('reception');
  await shot(page, 'r01-login');
  reception = await newUser(browser, 'reception', /\/reception\/$/, { width: 1440, height: 900 });
  await shot(reception, 'r02-report-empty');
  await reception.getByRole('button', { name: '前日の行を引き継ぐ' }).click();
  await toast(reception, /行引き継ぎました/);
  await reception.getByRole('button', { name: '＋ 行を追加' }).click();
  const d = dialog(reception);
  await d.getByRole('button', { name: 'か', exact: true }).click();
  await d.getByRole('button', { name: 'かや工業' }).click();
  await d.getByLabel('現場').selectOption({ label: '北区造成' });
  await d.getByLabel('車番').fill('5678');
  await d.getByLabel('品名').selectOption({ label: '残土' });
  await d.getByLabel('車格').selectOption({ label: '10t' });
  await shot(reception, 'r03-row-dialog');
  await d.getByRole('button', { name: '追加する' }).click();
  await toast(reception, /行を追加しました/);
  await nowCell(reception, '1234').click(); await toast(reception, /を記入しました$/);
  await reception.getByLabel('1234 を車列に選ぶ').check(); await reception.getByLabel('5678 を車列に選ぶ').check();
  await shot(reception, 'r04-convoy');
  await reception.getByRole('button', { name: /選んだ 2 行に今の時刻で記入/ }).click(); await toast(reception, /車列 2 台/);
  await nowCell(reception, '2222').click(); await toast(reception, /を記入しました$/);
  await reception.waitForTimeout(3500);
  await shot(reception, 'r05-report-filled');
  await nowCell(reception, '5678').locator('button').first().click();
  await shot(reception, 'r06-trip-menu');
  await dialog(reception).getByRole('button', { name: '草（草根）' }).click(); await toast(reception, /印を草/);
  const past = row(reception, '1234').locator('td').nth(4);
  await past.click();
  if (await dialog(reception).getByText('前の時間帯に後から記入します').isVisible().catch(() => false)) { await shot(reception, 'r07-add-past'); await dialog(reception).getByRole('button', { name: '閉じる' }).first().click().catch(() => reception.keyboard.press('Escape')); }
  else await reception.keyboard.press('Escape');
  await reception.getByRole('button', { name: '伝票を発行' }).click();
  await dialog(reception).getByRole('button', { name: /かや工業\s*北区造成/ }).click();
  await shot(reception, 'r08-slip-dialog');
  await dialog(reception).getByRole('button', { name: 'サイン用タブレットへ送る' }).click(); await toast(reception, /タブレットへ送りました/);
  await reception.getByRole('link', { name: '伝票一覧' }).click();
  await expect(reception.getByText('サイン待ち')).toBeVisible();

  const tablet = await newUser(browser, 'tablet1', /\/terminal\/$/, { width: 1280, height: 800 });
  await expect(tablet.getByText('かや工業 様')).toBeVisible();
  const box = (await tablet.getByLabel('サインの枠').boundingBox())!;
  await tablet.mouse.move(box.x + 120, box.y + 150); await tablet.mouse.down();
  for (let i = 1; i <= 30; i++) await tablet.mouse.move(box.x + 120 + i * 22, box.y + 150 + Math.sin(i / 2) * 50);
  await tablet.mouse.up();
  await shot(tablet, 't02-sign', { full: true });
  await tablet.getByRole('button', { name: '確定する' }).click();
  await expect(tablet.getByText('ありがとうございました')).toBeVisible();
  await shot(tablet, 't03-done');
  await tablet.getByRole('button', { name: '待機画面へ' }).click();
  await shot(tablet, 't01-waiting');
  await tablet.context().close();
  await expect(dialog(reception).getByText('サインが確定しました')).toBeVisible({ timeout: 15000 });
  await shot(reception, 'r09-signed-print');
  await dialog(reception).getByRole('button', { name: 'あとで' }).click();

  await reception.getByRole('link', { name: '受入日報' }).click();
  await reception.getByRole('button', { name: '伝票を発行' }).click();
  await dialog(reception).getByRole('button', { name: /三幸工務店/ }).click();
  await dialog(reception).getByLabel('請求先').selectOption({ label: '岡山土建' });
  await dialog(reception).getByLabel('変更の理由（任意）').fill('元請へ請求');
  await shot(reception, 'r10-slip-billing-change');
  await expectPdfOpened(reception, () => dialog(reception).getByRole('button', { name: '紙伝票で印刷' }).click());
  await reception.getByRole('link', { name: '伝票一覧' }).click();
  await reception.waitForTimeout(800);
  await shot(reception, 'r11-slip-list');
});

test('本社編', async ({ browser }) => {
  const office = await newUser(browser, 'office', /\/office\/$/, { width: 1440, height: 900 });
  await shot(office, 'o01-dashboard');
  await office.getByRole('link', { name: '受入日報' }).click(); await office.waitForTimeout(1200);
  await shot(office, 'o02-report');
  await office.getByRole('link', { name: '伝票', exact: true }).click();
  const tr = office.locator('tbody tr').filter({ hasText: '三幸工務店' });
  await tr.getByRole('button', { name: 'スキャンを登録' }).click();
  await dialog(office).locator('input[type=file]').setInputFiles({ name: 'scan.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj\n3 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 595 842]>>endobj\ntrailer<</Root 1 0 R>>\n%%EOF\n') });
  await shot(office, 'o03-scan');
  await dialog(office).getByRole('button', { name: '登録する' }).click(); await toast(office, 'スキャンを登録しました');

  await office.getByRole('link', { name: '請求', exact: true }).click();
  await expect(office.getByRole('button', { name: /締めを実行/ })).toBeVisible();
  await shot(office, 'o04-billing-precheck');
  await office.getByRole('button', { name: /締めを実行/ }).click();
  await dialog(office).getByRole('button', { name: '締めを実行する' }).click(); await toast(office, /請求書 \d+ 件を作成しました/);
  await office.getByLabel('すべて選ぶ').check();
  await office.getByRole('button', { name: '選んだものを確認済にする' }).click(); await toast(office, /確認済にしました/);
  await expect(office.getByText('PDF 作成中')).toHaveCount(0, { timeout: 30000 });
  await shot(office, 'o05-invoices');
  await office.locator('tbody tr').filter({ hasText: 'かや工業' }).getByRole('link', { name: /^SF-/ }).click();
  await expect(office.getByText('■ 現場：')).toBeVisible();
  await shot(office, 'o06-invoice-detail', { full: true });
  await office.getByRole('link', { name: '← 請求の一覧へ' }).click();
  await office.getByLabel('すべて選ぶ').check();
  await office.getByRole('button', { name: '選んだものをメール送信' }).click();
  await expect(dialog(office).getByText(/宛先：/).first()).toBeVisible();
  await shot(office, 'o07-mail');
  await dialog(office).getByRole('button', { name: /件を送信する/ }).click(); await toast(office, /件を送信しました/);
  await dialog(office).getByRole('button', { name: '閉じる' }).last().click();

  const { lastMonthDate } = state();
  await office.getByRole('link', { name: '集計' }).click();
  const dates = office.locator('input[type=date]');
  await dates.nth(0).fill(`${lastMonth()}-01`); await dates.nth(1).fill(lastMonthDate);
  await expect(office.locator('tbody tr').first()).toBeVisible();
  await shot(office, 'o08-aggregates');
  await office.locator('tbody tr').filter({ hasText: 'かや工業' }).first().click();
  await expect(dialog(office).locator('tbody tr').first()).toBeVisible();
  await shot(office, 'o09-aggregates-trips');
  await office.keyboard.press('Escape');
  await office.context().close();
});

